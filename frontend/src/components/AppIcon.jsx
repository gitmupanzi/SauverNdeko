export default function AppIcon({ name, size = 16, className = "" }) {
  const semantic = typeof name === "string" && name.startsWith("bi-") ? name.slice(3) : name;
  const key = aliases[name] || aliases[semantic] || semantic;
  const paths = lineAwesomePaths[key];
  if (!paths) return null;
  return <svg className={"app-icon " + className} data-icon={key} data-icon-provider="icons8-line-awesome" width={size} height={size} viewBox="0 0 32 32" fill="currentColor" aria-hidden="true" focusable="false">
    {paths.map((d, index) => <path key={index} d={d} />)}
  </svg>;
}
